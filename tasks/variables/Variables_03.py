"""
ЗАДАЧА: Variables_03

Описание:

Ты получаешь длительность видеозвонка по частям:

- hours = 1
- minutes = 47
- seconds = 35

Нужно:

1. Перевести всю длительность в секунды.
2. Отдельно посчитать полное количество минут.
3. Сформировать строку отчёта:
   "Звонок длился 1 ч 47 мин 35 сек (6455 секунд)"

Подсказки:

- в одном часе 3600 секунд
- в одной минуте 60 секунд
"""

# Напиши решение ниже.

hours = 1
minutes = 47
seconds = 35

total_seconds = hours * 3600 + minutes * 60 + seconds
total_minutes = hours * 60 + minutes

print(f"Звонок длился {hours} ч {minutes} мин {seconds} сек ({total_seconds} секунд)")
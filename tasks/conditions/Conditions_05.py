"""
ЗАДАЧА: Conditions_05

Описание:

Ты проверяешь возможность входа в административную панель.

Дано:

- role = " editor "
- is_blocked = False

Правила:

- если пользователь заблокирован, доступ запрещён
- если пользователь не заблокирован и его роль `admin` или `editor`, доступ разрешён
- в остальных случаях доступ запрещён

Нужно:

1. Нормализовать роль пользователя
2. Проверить доступ
3. Вывести:
   - "Доступ в админ-панель разрешён"
   - или "Доступ в админ-панель запрещён"

Подсказки:

- используй `strip()` и `lower()`
- можно использовать `or` или `in`
"""

# Напиши решение ниже.

role = " editor "
is_blocked = False
role = role and role.strip().lower()
has_access = not is_blocked and role in ("admin", "editor")

print("Доступ в админ-панель разрешён" if has_access else "Доступ в админ-панель запрещён")